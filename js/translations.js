let currentLang = localStorage.getItem('language') || 'en';

function translatePage(lang) {
    const elements = document.querySelectorAll('[data-i18n]');
    
    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (i18Obj[lang] && i18Obj[lang][key]) {
            if (element.tagName === 'INPUT' && element.placeholder !== undefined) {
                element.placeholder = i18Obj[lang][key];
            } else if (element.tagName === 'IMG' && element.alt !== undefined) {
                element.alt = i18Obj[lang][key];
            } else if (element.tagName === 'BUTTON' && element.value !== undefined) {
                element.value = i18Obj[lang][key];
            } else {
                element.textContent = i18Obj[lang][key];
            }
        }
    });
    
    updateActiveLanguageButton(lang);
    localStorage.setItem('language', lang);
    currentLang = lang;
    
    if (window.ToastManager) {
        window.ToastManager.show(`Язык: ${lang === 'en' ? 'English' : 'Русский'}`, 'info', 1500);
    }
    
    updateDynamicContent(lang);
}

function updateDynamicContent(lang) {
    document.querySelectorAll('.add-to-cart-btn').forEach(btn => {
        if (btn.textContent.includes('В корзину') || btn.textContent.includes('Add to cart')) {
            btn.textContent = i18Obj[lang]['add-to-cart'] || (lang === 'ru' ? '🛒 В корзину' : '🛒 Add to cart');
        }
    });
    
    document.querySelectorAll('.card-stock').forEach(el => {
        const isInStock = el.classList.contains('in-stock');
        if (isInStock) {
            el.innerHTML = i18Obj[lang]['in-stock'] || (lang === 'ru' ? '✓ В наличии' : '✓ In stock');
        } else {
            el.innerHTML = i18Obj[lang]['out-of-stock'] || (lang === 'ru' ? '✗ Нет в наличии' : '✗ Out of stock');
        }
    });
    
    document.querySelectorAll('select option').forEach(option => {
        const key = option.getAttribute('data-i18n');
        if (key && i18Obj[lang][key]) {
            option.textContent = i18Obj[lang][key];
        }
    });
}

function updateActiveLanguageButton(lang) {
    const langBtns = document.querySelectorAll('.lang-btn');
    langBtns.forEach(btn => {
        if (btn.dataset.lang === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });
}

function initLanguageSwitcher() {
    const savedLang = localStorage.getItem('language');
    if (savedLang && (savedLang === 'en' || savedLang === 'ru')) {
        translatePage(savedLang);
    } else {
        translatePage('en');
    }
}

function createLanguageSwitcher() {
    if (document.querySelector('.language-switcher')) return;
    
    const langSwitcher = document.createElement('div');
    langSwitcher.className = 'language-switcher';
    langSwitcher.innerHTML = `
        <button class="lang-btn" data-lang="en">EN</button>
        <button class="lang-btn" data-lang="ru">RU</button>
    `;
    
    const headerRight = document.querySelector('.header-line .nav-right');
    if (headerRight) {
        headerRight.appendChild(langSwitcher);
    } else {
        const headerLine = document.querySelector('.header-line');
        if (headerLine) {
            headerLine.appendChild(langSwitcher);
        }
    }
    
    const langBtns = document.querySelectorAll('.lang-btn');
    langBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            const lang = btn.dataset.lang;
            translatePage(lang);
        });
    });
}

